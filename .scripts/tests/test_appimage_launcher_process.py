#!/usr/bin/env python3
"""Tests for packaging/appimage/apprun-handoff.py: the name Kartend runs under.

linuxdeploy's AppRun ends in `exec "$this_dir"/AppRun.wrapped "$@"`, and the
kernel names the process after that link, so the AppImage ran as
"AppRun.wrapped". build-appimage.sh runs apprun-handoff.py on the AppDir right
after linuxdeploy so that AppRun executes usr/bin/kartend itself.

These tests build a private temporary AppDir: a tiny static x86_64 ELF as
usr/bin/kartend (it writes a fixed line to stdout, then waits for a signal),
AppRun.wrapped linking to it, the Qt-plugin hook exactly as build-appimage.sh
writes it, and an AppRun as linuxdeploy generates it. They start AppRun before
and after the rewrite, wait with a deadline for the ELF's line on that child's
own stdout pipe, and only then read /proc/<pid> of that one process: comm (the
name), cmdline (the forwarded arguments) and environ (the scrubbed Qt
variables). Every started process is killed and reaped in cleanup. Wrappers
that are not the expected one must be refused and left unchanged.

Qt's usage line ("Usage: %1 [options]") names argument zero, not the file
the kernel ran, so the rewritten AppRun also sets argument zero to kartend
(`exec -a`). When KARTEND_EXECUTABLE names the built kartend (CMake passes
it), the --help tests copy it into a second AppDir under a directory named
like the AppImage runtime's mount point (.mount_...), run AppRun --help with
a private HOME and XDG directories on the offscreen platform, and check the
first line of its stdout.

The same tests start AppRun with and without QT_QPA_PLATFORMTHEME: the hook
passes a caller's theme on and supplies none of its own.

TestAppImageQtPluginStaging runs the Qt plugin steps of build-appimage.sh
(qt-plugins.sh, sourced as the builder sources it) on a fixture plugin tree:
the XDG desktop portal theme lands at usr/plugins/platformthemes, a plugin the
selected Qt lacks stops the staging instead of being taken from a host Qt, and
the post-bundling check notices a lost one.

No AppImage is built, mounted or run here.

stdlib unittest — pytest is not available in CI. Run directly
(`python3 .scripts/tests/test_appimage_launcher_process.py`) or via
`python3 -m unittest`.
"""
from __future__ import annotations

import os
import pathlib
import platform
import re
import select
import shutil
import signal
import stat
import struct
import subprocess
import sys
import tempfile
import time
import unittest

REPO = pathlib.Path(__file__).resolve().parent.parent.parent
APPIMAGE_DIR = REPO / "packaging" / "appimage"
HANDOFF = APPIMAGE_DIR / "apprun-handoff.py"
BUILDER = APPIMAGE_DIR / "build-appimage.sh"

HOOK_NAME = "kartend-own-qt.sh"
QT_VARIABLES = ("QT_PLUGIN_PATH", "QT_QPA_PLATFORM_PLUGIN_PATH", "QML_IMPORT_PATH", "QML2_IMPORT_PATH")
OLD_EXEC = 'exec "$this_dir"/AppRun.wrapped "$@"'
NEW_EXEC = 'exec -a kartend "$this_dir/usr/bin/kartend" "$@"'
# The line the first handoff wrote: the right file, but the mount path as argument zero.
PATH_EXEC = 'exec "$this_dir/usr/bin/kartend" "$@"'
# The built kartend, for the --help tests; set by the AppImageLauncherProcess registration.
KARTEND_EXECUTABLE = os.environ.get("KARTEND_EXECUTABLE", "")
# Like the AppImage runtime's mount point, /tmp/.mount_<name><random>.
MOUNT_DIR = ".mount_KartenQ1w2E3"

# What linuxdeploy writes as AppRun when the AppDir has apprun-hooks.
GENERATED_APPRUN = f"""#! /usr/bin/env bash

# autogenerated by linuxdeploy

# make sure errors in sourced scripts will cause this script to stop
set -e

this_dir="$(readlink -f "$(dirname "$0")")"

source "$this_dir"/apprun-hooks/"{HOOK_NAME}"

{OLD_EXEC}
"""

# Arguments a user could pass; none may be split, globbed or expanded.
ARGUMENTS = ["--help", "two words", "*", "$HOME", "", "; touch injected", "--"]
DEADLINE = 10.0
# Set for the launched process; the hook must leave it alone.
MARKER = "KARTEND_TEST_UNRELATED"
# The caller's choice of Qt platform theme; the hook must pass it on and never set one.
THEME_VARIABLE = "QT_QPA_PLATFORMTHEME"

# The plugin staging build-appimage.sh sources, and the pins it needs.
COMMON = APPIMAGE_DIR / "common.sh"
PLUGIN_STEPS = APPIMAGE_DIR / "qt-plugins.sh"
PORTAL_THEME = "platformthemes/libqxdgdesktopportal.so"


# What the fixture ELF writes to its stdout once it runs in userspace.
READY = b"kartend-fixture-ready\n"


def tiny_elf() -> bytes:
    """A static x86_64 executable that writes READY to stdout, then loops on pause(2) until a signal ends it.

    The write is its first instruction, so READY on the pipe means execve() has
    returned to userspace in the new image: comm, cmdline and environ are final.
    """
    base = 0x400000
    code = (
        bytes.fromhex("b801000000")  # mov eax, 1 (write)
        + bytes.fromhex("bf01000000")  # mov edi, 1 (stdout)
        + bytes.fromhex("488d3510000000")  # lea rsi, [rip + 16] (READY, after the loop)
        + bytes.fromhex("ba") + struct.pack("<I", len(READY))  # mov edx, len(READY)
        + bytes.fromhex("0f05")  # syscall
        + bytes.fromhex("b822000000" "0f05" "ebf7")  # mov eax, 34 (pause); syscall; jmp back
        + READY
    )
    header_size, phdr_size = 64, 56
    total = header_size + phdr_size + len(code)
    ident = b"\x7fELF\x02\x01\x01" + b"\x00" * 9
    header = struct.pack(
        "<16sHHIQQQIHHHHHH",
        ident, 2, 0x3E, 1, base + header_size + phdr_size, header_size, 0, 0,
        header_size, phdr_size, 1, 0, 0, 0,
    )
    phdr = struct.pack("<IIQQQQQQ", 1, 5, 0, base, base, total, total, 0x1000)
    return header + phdr + code


def builder_hook_text() -> str:
    """The hook as build-appimage.sh writes it (its here-document)."""
    text = BUILDER.read_text(encoding="utf-8")
    match = re.search(
        r'cat >"\$APPDIR/apprun-hooks/' + re.escape(HOOK_NAME) + r"\" <<'EOF'\n(.*?)\nEOF\n", text, re.S
    )
    if match is None:
        raise AssertionError(f"build-appimage.sh no longer writes apprun-hooks/{HOOK_NAME}")
    return match.group(1) + "\n"


@unittest.skipUnless(sys.platform.startswith("linux"), "reads /proc; Linux only")
@unittest.skipUnless(platform.machine() == "x86_64", "the fixture ELF is x86_64, like the AppImage")
class TestAppImageLauncherProcess(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory(prefix="kartend-apprun-")
        self.addCleanup(self._tmp.cleanup)
        self.appdir = pathlib.Path(self._tmp.name) / "AppDir"
        (self.appdir / "usr" / "bin").mkdir(parents=True)
        (self.appdir / "apprun-hooks").mkdir()
        self.executable = self.appdir / "usr" / "bin" / "kartend"
        self.executable.write_bytes(tiny_elf())
        self.executable.chmod(0o755)
        os.symlink("usr/bin/kartend", self.appdir / "AppRun.wrapped")
        (self.appdir / "apprun-hooks" / HOOK_NAME).write_text(builder_hook_text(), encoding="utf-8")
        self.apprun = self.appdir / "AppRun"
        self.write_apprun(GENERATED_APPRUN)

    def write_apprun(self, text: str, mode: int = 0o755) -> None:
        self.apprun.write_text(text, encoding="utf-8")
        self.apprun.chmod(mode)

    def run_handoff(self) -> subprocess.CompletedProcess:
        return subprocess.run(
            [sys.executable, "-I", str(HANDOFF), str(self.appdir)],
            capture_output=True, text=True, check=False, timeout=DEADLINE,
        )

    def launch(self, theme: str | None = None) -> dict:
        """Start AppRun, wait for the ELF's READY on that child's stdout, then read its /proc entry.

        theme: the caller's QT_QPA_PLATFORMTHEME, or None to start without one.
        """
        env = {key: value for key, value in os.environ.items() if key not in QT_VARIABLES and key != THEME_VARIABLE}
        for key in QT_VARIABLES:
            env[key] = "/caller/system-qt/plugins"
        env[MARKER] = "kept"
        if theme is not None:
            env[THEME_VARIABLE] = theme
        process = subprocess.Popen(
            [str(self.apprun), *ARGUMENTS], env=env, cwd=self._tmp.name,
            stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            start_new_session=True,
        )
        self.addCleanup(self.close, process)
        self.addCleanup(self.stop, process)  # runs first: kill and reap, then close the pipes
        self.wait_ready(process)
        proc = pathlib.Path("/proc") / str(process.pid)
        self.assertEqual(os.readlink(proc / "exe"), os.path.realpath(self.executable))
        # Only the variables under test are kept, so a failure never prints the rest.
        environ = {}
        for entry in (proc / "environ").read_bytes().split(b"\0"):
            key, _, value = entry.decode().partition("=")
            if key in QT_VARIABLES or key in (MARKER, THEME_VARIABLE):
                environ[key] = value
        return {
            "exe": os.readlink(proc / "exe"),
            "comm": (proc / "comm").read_text().strip(),
            "argv": [arg.decode() for arg in (proc / "cmdline").read_bytes().split(b"\0")[:-1]],
            "environ": environ,
        }

    def wait_ready(self, process: subprocess.Popen) -> None:
        """Read the child's stdout until it is exactly READY; fail on early exit, other output or timeout."""
        received = b""
        deadline = time.monotonic() + DEADLINE
        while received != READY:
            if not READY.startswith(received):
                self.fail_launch(process, f"unexpected output before readiness: {received[:200]!r}")
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                self.fail_launch(process, f"no readiness signal within {DEADLINE} s (got {received!r})")
            readable, _, _ = select.select([process.stdout], [], [], remaining)
            if not readable:
                continue
            chunk = os.read(process.stdout.fileno(), len(READY))
            if not chunk:
                self.fail_launch(process, f"stdout closed before readiness (got {received!r})")
            received += chunk

    def fail_launch(self, process: subprocess.Popen, reason: str) -> None:
        self.stop(process)
        status = process.returncode
        if status is not None and status < 0:
            try:
                status = f"signal {signal.Signals(-status).name}"
            except ValueError:
                status = f"signal {-status}"
        stderr = process.stderr.read().decode(errors="replace")[-2000:]
        self.fail(f"AppRun: {reason}; exit status {status}; stderr: {stderr}")

    @staticmethod
    def stop(process: subprocess.Popen) -> None:
        if process.poll() is None:
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
        process.wait(timeout=DEADLINE)

    @staticmethod
    def close(process: subprocess.Popen) -> None:
        process.stdout.close()
        process.stderr.close()

    def assert_hook_ran(self, seen: dict) -> None:
        for key in QT_VARIABLES:
            self.assertNotIn(key, seen["environ"], f"{key} reached the executable")
        self.assertEqual(seen["environ"].get(MARKER), "kept")

    def test_generated_launcher_runs_as_apprun_wrapped(self) -> None:
        seen = self.launch()
        self.assertEqual(seen["comm"], "AppRun.wrapped")
        self.assertEqual(seen["argv"][1:], ARGUMENTS)
        self.assert_hook_ran(seen)

    def test_changed_launcher_runs_as_kartend(self) -> None:
        result = self.run_handoff()
        self.assertEqual(result.returncode, 0, result.stderr)
        seen = self.launch()
        self.assertEqual(seen["comm"], "kartend")
        # The file run is still the AppDir's own (launch() checks /proc/<pid>/exe); only argument zero is the name.
        self.assertEqual(seen["exe"], str(self.appdir.resolve() / "usr" / "bin" / "kartend"))
        self.assertEqual(seen["argv"], ["kartend", *ARGUMENTS])
        self.assert_hook_ran(seen)
        self.assertFalse((pathlib.Path(self._tmp.name) / "injected").exists())

    def test_caller_theme_passes_through_and_none_is_added(self) -> None:
        # The portal theme is bundled for callers who ask for it; the hook neither drops
        # an explicit choice nor makes one when the caller has none.
        for handoff in (False, True):
            with self.subTest(handoff=handoff):
                if handoff:
                    result = self.run_handoff()
                    self.assertEqual(result.returncode, 0, result.stderr)
                for theme in ("xdgdesktopportal", "gtk3"):
                    seen = self.launch(theme=theme)
                    self.assertEqual(seen["environ"].get(THEME_VARIABLE), theme)
                    self.assert_hook_ran(seen)
                seen = self.launch(theme=None)
                self.assertNotIn(THEME_VARIABLE, seen["environ"], "the hook supplied a platform theme")
                self.assert_hook_ran(seen)

    def help_appdir(self) -> pathlib.Path:
        """An AppDir under a .mount_-like directory with the built kartend as usr/bin/kartend."""
        if not KARTEND_EXECUTABLE:
            self.skipTest("KARTEND_EXECUTABLE is not set (the CMake registration sets it)")
        source = pathlib.Path(KARTEND_EXECUTABLE)
        self.assertTrue(source.is_file() and os.access(source, os.X_OK), f"not an executable file: {source}")
        appdir = pathlib.Path(self._tmp.name) / MOUNT_DIR
        (appdir / "usr" / "bin").mkdir(parents=True)
        (appdir / "apprun-hooks").mkdir()
        shutil.copy2(source, appdir / "usr" / "bin" / "kartend")
        os.symlink("usr/bin/kartend", appdir / "AppRun.wrapped")
        (appdir / "apprun-hooks" / HOOK_NAME).write_text(builder_hook_text(), encoding="utf-8")
        (appdir / "AppRun").write_text(GENERATED_APPRUN, encoding="utf-8")
        (appdir / "AppRun").chmod(0o755)
        return appdir

    def help_first_line(self, appdir: pathlib.Path) -> str:
        """Run AppRun --help offscreen with private HOME/XDG paths; return the first stdout line."""
        private = pathlib.Path(self._tmp.name) / "home"
        env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "HOME": str(private), "LANG": "C.UTF-8"}
        for key, sub in (("XDG_CONFIG_HOME", "config"), ("XDG_DATA_HOME", "data"),
                         ("XDG_CACHE_HOME", "cache"), ("XDG_STATE_HOME", "state"), ("XDG_RUNTIME_DIR", "run")):
            env[key] = str(private / sub)
            (private / sub).mkdir(parents=True, mode=0o700, exist_ok=True)
        env["QT_QPA_PLATFORM"] = "offscreen"
        for key in QT_VARIABLES:
            env[key] = "/caller/system-qt/plugins"  # the hook must drop these
        result = subprocess.run(
            [str(appdir / "AppRun"), "--help"], env=env, cwd=self._tmp.name,
            stdin=subprocess.DEVNULL, capture_output=True, check=False, timeout=DEADLINE,
        )
        stdout = result.stdout.decode(errors="replace")
        self.assertEqual(result.returncode, 0, f"--help exited {result.returncode}; "
                         f"stderr: {result.stderr.decode(errors='replace')[-2000:]}")
        self.assertTrue(stdout, "--help wrote nothing to stdout")
        line = stdout.splitlines()[0]
        print(f"\n  --help first line: {line.replace(self._tmp.name, '<tmp>')}", file=sys.stderr)
        return line

    @staticmethod
    def usage_problem(line: str) -> str | None:
        """Why this usage line does not name kartend plainly, or None."""
        if not line.startswith("Usage: "):
            return "not a usage line"
        if "AppRun.wrapped" in line:
            return "names AppRun.wrapped"
        if ".mount_" in line or "/" in line:
            return "names a path in the mount directory"
        if line != "Usage: kartend [options]":
            return "does not name kartend"
        return None

    def test_help_usage_line_before_and_after_the_handoff(self) -> None:
        appdir = self.help_appdir()
        apprun = appdir / "AppRun"
        generated = self.help_first_line(appdir)
        self.assertEqual(self.usage_problem(generated), "names AppRun.wrapped", generated)
        apprun.write_text(GENERATED_APPRUN.replace(OLD_EXEC, PATH_EXEC), encoding="utf-8")
        first_handoff = self.help_first_line(appdir)
        self.assertEqual(self.usage_problem(first_handoff), "names a path in the mount directory", first_handoff)
        apprun.write_text(GENERATED_APPRUN, encoding="utf-8")
        result = subprocess.run(
            [sys.executable, "-I", str(HANDOFF), str(appdir)],
            capture_output=True, text=True, check=False, timeout=DEADLINE,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn(NEW_EXEC, apprun.read_text(encoding="utf-8").split("\n"))
        fixed = self.help_first_line(appdir)
        self.assertIsNone(self.usage_problem(fixed), fixed)

    def test_rewrite_changes_only_the_exec_line_and_keeps_the_mode(self) -> None:
        self.write_apprun(GENERATED_APPRUN, mode=0o750)
        result = self.run_handoff()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.apprun.read_text(encoding="utf-8"), GENERATED_APPRUN.replace(OLD_EXEC, NEW_EXEC))
        self.assertEqual(stat.S_IMODE(self.apprun.stat().st_mode), 0o750)
        self.assertEqual(sorted(p.name for p in self.appdir.iterdir() if p.name.startswith(".")), [])

    def assert_refused(self, reason: str) -> None:
        before = self.apprun.read_bytes() if self.apprun.exists() else None
        result = self.run_handoff()
        self.assertEqual(result.returncode, 1, f"{reason}: {result.stdout}{result.stderr}")
        self.assertIn("apprun-handoff:", result.stderr)
        after = self.apprun.read_bytes() if self.apprun.exists() else None
        self.assertEqual(after, before, f"{reason}: AppRun was changed")

    def test_unexpected_wrappers_are_refused_unchanged(self) -> None:
        hook_line = f'source "$this_dir"/apprun-hooks/"{HOOK_NAME}"'
        cases = {
            "no exec line": GENERATED_APPRUN.replace(OLD_EXEC + "\n", ""),
            "exec line twice": GENERATED_APPRUN + OLD_EXEC + "\n",
            "exec without arguments": GENERATED_APPRUN.replace(OLD_EXEC, 'exec "$this_dir"/AppRun.wrapped'),
            "command after exec": GENERATED_APPRUN + "echo after\n",
            "other use of AppRun.wrapped": GENERATED_APPRUN.replace("set -e", 'set -e\nls "$this_dir"/AppRun.wrapped'),
            "hook not sourced": GENERATED_APPRUN.replace(hook_line + "\n", ""),
            "already rewritten": GENERATED_APPRUN.replace(OLD_EXEC, NEW_EXEC),
            "rewritten by the first handoff": GENERATED_APPRUN.replace(OLD_EXEC, PATH_EXEC),
            "not a shell script": "\x7fELF" + GENERATED_APPRUN,
        }
        for reason, text in cases.items():
            with self.subTest(reason=reason):
                self.write_apprun(text)
                self.assert_refused(reason)

    def test_missing_wrapper_is_refused(self) -> None:
        self.apprun.unlink()
        self.assert_refused("no AppRun")

    def test_linked_wrapper_is_refused(self) -> None:
        self.apprun.unlink()
        os.symlink("usr/bin/kartend", self.apprun)
        self.assert_refused("AppRun is a link")
        self.assertTrue(self.apprun.is_symlink())

    def test_wrapped_link_to_another_file_is_refused(self) -> None:
        other = self.appdir / "usr" / "bin" / "other"
        other.write_bytes(tiny_elf())
        other.chmod(0o755)
        (self.appdir / "AppRun.wrapped").unlink()
        os.symlink("usr/bin/other", self.appdir / "AppRun.wrapped")
        self.assert_refused("AppRun.wrapped leads elsewhere")

    def test_builder_runs_the_handoff_after_bundling_and_before_the_checks(self) -> None:
        text = BUILDER.read_text(encoding="utf-8")
        bundling = text.index('"$LINUXDEPLOY" --appdir "$APPDIR"')
        handoff = text.index('python3 "$HERE/apprun-handoff.py" "$APPDIR" ||')
        checks = text.index('step "5/9 check the AppDir"')
        self.assertLess(bundling, handoff)
        self.assertLess(handoff, checks)
        self.assertEqual(text.count("apprun-handoff.py"), 2)  # the call and its comment
        self.assertIn(f"grep -qxF '{NEW_EXEC}' \"$APPDIR/AppRun\"", text)


@unittest.skipUnless(sys.platform.startswith("linux"), "the AppImage is built on Linux")
class TestAppImageQtPluginStaging(unittest.TestCase):
    """The Qt plugin steps of build-appimage.sh (qt-plugins.sh), run on a fixture Qt plugin tree.

    The functions run in bash exactly as the builder sources them. The fixture
    root holds one small file per listed plugin, each with its own content, so
    a copy from anywhere else would show. A second tree stands for a Qt on
    the host (named by QT_PLUGIN_PATH and placed next to the fixture root);
    it must never be used.
    """

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory(prefix="kartend-qt-plugins-")
        self.addCleanup(self._tmp.cleanup)
        base = pathlib.Path(self._tmp.name)
        self.root = base / "qt" / "plugins"
        self.host = base / "host-qt" / "plugins"
        self.appdir = base / "AppDir"
        self.plugins = self.listed_plugins()
        for plugin in self.plugins:
            self.write_plugin(self.root, plugin, f"pinned {plugin}\n")
            self.write_plugin(self.host, plugin, f"host {plugin}\n")

    @staticmethod
    def write_plugin(root: pathlib.Path, plugin: str, text: str) -> None:
        path = root / plugin
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        path.chmod(0o644)

    def run_steps(self, snippet: str, *args: str) -> subprocess.CompletedProcess:
        """Source common.sh and qt-plugins.sh as build-appimage.sh does (set -euo pipefail), then run snippet."""
        script = 'set -euo pipefail; . "$1"; . "$2"; shift 2; ' + snippet
        env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "LANG": "C.UTF-8",
               "QT_PLUGIN_PATH": str(self.host), "KARTEND_APPIMAGE_PROG": "build-appimage"}
        return subprocess.run(
            ["bash", "-c", script, "bash", str(COMMON), str(PLUGIN_STEPS), *args],
            env=env, cwd=self._tmp.name, capture_output=True, text=True, check=False, timeout=DEADLINE,
        )

    def listed_plugins(self) -> list[str]:
        """The plugin list as the sourced script defines it."""
        result = self.run_steps('printf "%s\\n" "${KARTEND_APPIMAGE_QT_PLUGINS[@]}"')
        self.assertEqual(result.returncode, 0, result.stderr)
        return result.stdout.split()

    def stage(self) -> subprocess.CompletedProcess:
        """Stage from the fixture root; on success stdout lists the plugin directories for linuxdeploy."""
        return self.run_steps(
            'kartend_appimage_stage_qt_plugins "$1" "$2"; printf "%s\\n" "${KARTEND_APPIMAGE_QT_PLUGIN_DIRS[@]}"',
            str(self.root), str(self.appdir),
        )

    def check(self) -> subprocess.CompletedProcess:
        return self.run_steps('kartend_appimage_check_qt_plugins "$1"', str(self.appdir))

    def test_the_portal_theme_is_on_the_list(self) -> None:
        self.assertIn(PORTAL_THEME, self.plugins)
        self.assertEqual(len(self.plugins), len(set(self.plugins)))

    def test_staging_copies_the_portal_theme_from_the_selected_qt(self) -> None:
        result = self.stage()
        self.assertEqual(result.returncode, 0, result.stderr)
        staged = self.appdir / "usr" / "plugins" / PORTAL_THEME
        self.assertEqual(staged.read_text(encoding="utf-8"), f"pinned {PORTAL_THEME}\n")
        self.assertEqual(stat.S_IMODE(staged.stat().st_mode), 0o755)
        for plugin in self.plugins:
            with self.subTest(plugin=plugin):
                self.assertEqual((self.appdir / "usr" / "plugins" / plugin).read_text(encoding="utf-8"),
                                 f"pinned {plugin}\n")
        # linuxdeploy is told to bundle what the theme needs (QtDBus) through this list.
        dirs = result.stdout.split("\n")[:-1]
        self.assertIn(str(self.appdir / "usr" / "plugins" / "platformthemes"), dirs)
        self.assertEqual(len(dirs), len(set(dirs)))
        check = self.check()
        self.assertEqual(check.returncode, 0, check.stderr)

    def test_staging_stops_when_the_selected_qt_lacks_the_portal_theme(self) -> None:
        (self.root / PORTAL_THEME).unlink()
        result = self.stage()
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn(f"has no plugin {PORTAL_THEME}", result.stderr)
        self.assertFalse((self.appdir / "usr" / "plugins" / PORTAL_THEME).exists(),
                         "the portal theme was taken from somewhere other than the selected Qt")
        self.assertEqual(result.stdout, "")

    def test_staging_refuses_a_missing_plugin_root(self) -> None:
        shutil.rmtree(self.root)
        result = self.stage()
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("does not exist", result.stderr)
        self.assertFalse((self.appdir / "usr" / "plugins").exists())

    def test_check_detects_a_lost_or_empty_portal_theme(self) -> None:
        staged = self.appdir / "usr" / "plugins" / PORTAL_THEME
        for damage in ("removed", "emptied", "replaced by a directory"):
            with self.subTest(damage=damage):
                result = self.stage()
                self.assertEqual(result.returncode, 0, result.stderr)
                if damage == "removed":
                    staged.unlink()
                elif damage == "emptied":
                    staged.write_bytes(b"")
                else:
                    staged.unlink()
                    staged.mkdir()
                    (staged / "x").write_text("x", encoding="utf-8")
                check = self.check()
                self.assertEqual(check.returncode, 1, check.stdout + check.stderr)
                self.assertIn(f"the AppDir lost the Qt plugin {PORTAL_THEME}", check.stderr)
                shutil.rmtree(self.appdir)

    def test_builder_stages_and_checks_through_these_steps(self) -> None:
        text = BUILDER.read_text(encoding="utf-8")
        self.assertIn('. "$HERE/qt-plugins.sh"', text)
        stage = text.index('kartend_appimage_stage_qt_plugins "$QT_PLUGIN_DIR" "$APPDIR"')
        bundling = text.index('"$LINUXDEPLOY" --appdir "$APPDIR"')
        check = text.index('kartend_appimage_check_qt_plugins "$APPDIR"')
        self.assertLess(stage, bundling)
        self.assertLess(bundling, check)
        self.assertIn('plugin_dirs=("${KARTEND_APPIMAGE_QT_PLUGIN_DIRS[@]}")', text)
        # The plugin root is the pinned Qt's own, asked of its qmake.
        self.assertIn('QT_PLUGIN_DIR="$("$QT_DIR/bin/qmake" -query QT_INSTALL_PLUGINS)"', text)


